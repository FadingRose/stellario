fn now_iso() -> String {
    chrono::Utc::now().format("%Y-%m-%dT%H:%M:%SZ").to_string()
}

fn edge_kind_str(k: EdgeKind) -> &'static str {
    match k {
        EdgeKind::Parent => "parent",
        EdgeKind::Supersede => "supersede",
        EdgeKind::DeriveFrom => "derive_from",
        EdgeKind::Validate => "validate",
        EdgeKind::Constrain => "constrain",
    }
}

fn parse_edge_kind(s: &str) -> Option<EdgeKind> {
    match s {
        "parent" => Some(EdgeKind::Parent),
        "supersede" => Some(EdgeKind::Supersede),
        "derive_from" => Some(EdgeKind::DeriveFrom),
        "validate" => Some(EdgeKind::Validate),
        "constrain" => Some(EdgeKind::Constrain),
        _ => None,
    }
}

fn scalar_str(v: &automerge::ScalarValue) -> String {
    match v {
        automerge::ScalarValue::Str(s) => s.to_string(),
        automerge::ScalarValue::Int(i) => i.to_string(),
        automerge::ScalarValue::Boolean(b) => b.to_string(),
        other => format!("{:?}", other),
    }
}

fn get_str(doc: &AutoCommit, obj: &automerge::ObjId, key: &str) -> Result<Option<String>> {
    Ok(doc
        .get(obj, key)?
        .and_then(|(v, _)| match v {
            Value::Scalar(s) => Some(scalar_str(s.as_ref())),
            _ => None,
        }))
}

fn get_bool(doc: &AutoCommit, obj: &automerge::ObjId, key: &str) -> Result<Option<bool>> {
    Ok(doc.get(obj, key)?.and_then(|(v, _)| match v {
        Value::Scalar(s) => match s.as_ref() {
            automerge::ScalarValue::Boolean(b) => Some(*b),
            _ => None,
        },
        _ => None,
    }))
}

fn get_list_strings(doc: &AutoCommit, obj: &automerge::ObjId, key: &str) -> Result<Vec<String>> {
    let Some((_, list)) = doc.get(obj, key)? else {
        return Ok(vec![]);
    };
    let len = doc.length(&list);
    let mut out = Vec::with_capacity(len);
    for i in 0..len {
        if let Some((Value::Scalar(s), _)) = doc.get(&list, i)? {
            out.push(scalar_str(s.as_ref()));
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sequential_id_increments() {
        let mut s = AutomergeStorage::new();
        s.declare_volume("active", &VolumeDef::default()).unwrap();
        let (id1, _) = s.write("active", None, "first", &[], &[], "a", "init", &[], &[]).unwrap();
        let (id2, _) = s.write("active", None, "second", &[], &[], "a", "init", &[], &[]).unwrap();
        assert_eq!(id1, "1");
        assert_eq!(id2, "2");
    }

    #[test]
    fn random_id_is_hex() {
        let mut s = AutomergeStorage::new();
        s.declare_volume("draft", &VolumeDef {
            id_strategy: IdStrategy::Random,
            supersede: SupersedePolicy::Allowed,
        })
        .unwrap();
        let (id, _) = s.write("draft", None, "x", &[], &[], "a", "init", &[], &[]).unwrap();
        assert!(id.chars().all(|c| c.is_ascii_hexdigit()), "random id should be hex, got {}", id);
        assert_ne!(id.parse::<usize>().ok(), Some(1), "random id should not be sequential 1");
    }

    #[test]
    fn supersede_forbidden_rejects_supersede() {
        let mut s = AutomergeStorage::new();
        // handover: audit trail, no overturning allowed
        s.declare_volume("handover", &VolumeDef {
            id_strategy: IdStrategy::Sequential,
            supersede: SupersedePolicy::Forbidden,
        })
        .unwrap();
        let (_, h1) = s.write("handover", None, "session 1 log", &[], &[], "a", "log", &[], &[]).unwrap();
        // Attempt to supersede the handover entry — must be rejected.
        let supersede_edge = Edge {
            from: String::new(),
            to: h1.clone(),
            kind: EdgeKind::Supersede,
            reason: "try to overturn audit".into(),
        };
        let result = s.write("handover", Some("1"), "overturn attempt", &[], &[], "a", "bad", &[], &[supersede_edge]);
        assert!(result.is_err(), "supersede must be rejected in a Forbidden volume");
    }

    #[test]
    fn supersede_allowed_accepts_supersede() {
        let mut s = AutomergeStorage::new();
        s.declare_volume("layer", &VolumeDef::default()).unwrap();
        let (_, h1) = s.write("layer", Some("1"), "v1 claim", &[], &[], "a", "init", &[], &[]).unwrap();
        let supersede_edge = Edge {
            from: String::new(),
            to: h1,
            kind: EdgeKind::Supersede,
            reason: "v1 was wrong".into(),
        };
        let result = s.write("layer", Some("1"), "v2 corrected", &[], &[], "a", "fix", &[], &[supersede_edge]);
        assert!(result.is_ok(), "supersede allowed in default volume");
    }

    #[test]
    fn find_by_tag_matches_all() {
        let mut s = AutomergeStorage::new();
        s.write("meta", Some("1"), "## A", &["type:design".into(), "module:core".into()], &[], "a", "i", &[], &[]).unwrap();
        s.write("meta", Some("2"), "## B", &["type:design".into(), "module:auth".into()], &[], "a", "i", &[], &[]).unwrap();
        s.write("meta", Some("3"), "## C", &["type:handoff".into()], &[], "a", "i", &[], &[]).unwrap();

        // AND filter: both tags
        let both = s.find_by_tag("meta", &["type:design".into(), "module:core".into()]).unwrap();
        assert_eq!(both.len(), 1);
        assert_eq!(both[0].id, "meta:1");

        let design = s.find_by_tag("meta", &["type:design".into()]).unwrap();
        assert_eq!(design.len(), 2);
    }

    #[test]
    fn volume_def_defaults_when_undeclared() {
        let s = AutomergeStorage::new();
        let def = s.volume_def("anything").unwrap();
        assert_eq!(def.id_strategy, IdStrategy::Sequential);
        assert_eq!(def.supersede, SupersedePolicy::Allowed);
    }
}
