#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn register_then_select_loads_meta() {
        let mut global = AutomergeStorage::new();
        let (id, _hash) = register_identity(
            &mut global,
            "edelweiss",
            "Edelweiss",
            "Primary engine agent. Handles Rust implementation + orchestration.",
            "bootstrap",
        )
        .unwrap();
        assert!(id.starts_with("1") || id == "1", "sequential id, got {}", id);

        let resolved = select_identity(&global, "edelweiss").unwrap();
        assert_eq!(resolved.identity, "name:edelweiss");
        assert_eq!(resolved.display, "Edelweiss");
        assert!(resolved.instance.starts_with("name:edelweiss#"));
        assert!(resolved.meta.contains("Primary engine agent"));
        assert_eq!(resolved.instance_hash.len(), 4);
    }

    #[test]
    fn two_concurrent_loads_mint_different_instances() {
        let mut global = AutomergeStorage::new();
        register_identity(&mut global, "art", "Art", "Visual asset agent.", "bootstrap").unwrap();

        let a = select_identity(&global, "art").unwrap();
        std::thread::sleep(std::time::Duration::from_micros(1100));
        let b = select_identity(&global, "art").unwrap();

        assert_eq!(a.identity, b.identity);
        assert_ne!(a.instance_hash, b.instance_hash, "concurrent loads must differ");
    }

    #[test]
    fn select_unknown_identity_errors() {
        let global = AutomergeStorage::new();
        assert!(select_identity(&global, "nobody").is_err());
    }

    #[test]
    fn identities_listed_by_name() {
        let mut global = AutomergeStorage::new();
        register_identity(&mut global, "edelweiss", "Edelweiss", "x", "b").unwrap();
        register_identity(&mut global, "art", "Art", "y", "b").unwrap();
        let names = list_identities(&global).unwrap();
        assert!(names.contains(&"edelweiss".to_string()));
        assert!(names.contains(&"art".to_string()));
    }
}
